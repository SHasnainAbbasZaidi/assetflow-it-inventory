  static List<String> modelsFor(String itemCategory, String deviceType) {
    final categoryModels = _models[itemCategory] ?? const {};
    final exact = categoryModels[deviceType] ?? const [];
    if (exact.isNotEmpty) return exact;

    final normalizedDevice = deviceType.toLowerCase();
    for (final entry in categoryModels.entries) {
      if (entry.key.toLowerCase().contains(normalizedDevice) ||
          normalizedDevice.contains(entry.key.toLowerCase())) {
        return entry.value;
      }
    }

    return const ['Custom Model'];
  }

  static List<String> allDeviceTypesForCategory(String itemCategory) {
    return (_models[itemCategory]?.keys.toList() ?? const ['Other'])
      ..sort((a, b) => a.toLowerCase().compareTo(b.toLowerCase()));
  }
